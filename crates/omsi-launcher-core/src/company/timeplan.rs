//! RosterFlow's timeplan (the planning, phase 1b; Luc: the company's planning should look and
//! work "exactly" like Optibus Planning): a line's running times and its timetable, made the
//! way a scheduler makes them.
//!
//! * **Running times** per day group (`lines::DAY_GROUPS`) and direction: the minutes a bus
//!   needs between two stops, in **time bands** from 00:00 to 36:00 (`RunSet`, `Band`) - the
//!   peak slower than the evening. Each segment of a trip takes the running time of the band
//!   the segment starts in (Optibus's "incremental application"), so one trip can cross bands.
//! * **Timepoints**: the stops a timetable shows a time at; the first and the last always are
//!   (`RunPlan::is_timepoint`). Every stop keeps its time in the game all the same.
//! * **Patterns**: a direction is a pattern. A line of the map's with more trips than two
//!   (a short run, a night variant) has more: each falls to the side (OUTBOUND / INBOUND)
//!   whose main direction it follows most (`sides`), and the columns of a side are the stops
//!   of all its patterns in order - a dash where a pattern skips one.
//! * **Trips** are the line's table (`lines::TableTrip`, its timetable as the game drives it:
//!   nothing is forked): generated by headway from a control point (`generate`, alternating
//!   headways such as "10,20" allowed), added one at a time, moved by their start or their
//!   headway (every later trip with them), a single time typed over (an override, shown as an
//!   offset against the running times: `offsets`).
//! * **Validation** (`issues`): overlapping trips, negative and zero running times, a pattern
//!   without stops, trips past 36:00.
//!
//! What is saved is the line itself (`LineDesign::timeplan` and its table), the way every
//! timetable of a company line is saved; `resync` lets the scheduling studio make its blocks
//! of the line anew once the timetable changed.

use super::model::Company;
use crate::lines::{self as reg, Direction, LineDesign, TableTrip};
use serde::{Deserialize, Serialize};

/// Where the time bands end: 36:00, so the service after midnight is covered.
pub const DAY_SPAN: f32 = 36.0 * 60.0;
/// A trip's first departure when there is none to follow.
pub const FIRST_TRIP: f32 = 6.0 * 60.0;

/// A line's timeplan: running times per day group and direction, and its timepoints.
#[derive(Serialize, Deserialize, Clone, Debug, PartialEq, Default)]
#[serde(default)]
pub struct RunPlan {
    pub sets: Vec<RunSet>,
    pub timepoints: Vec<Timepoints>,
}

/// The running times of one day group (`day`, an index into `DAY_GROUPS`) and one direction
/// (`dir`, a pattern): its time bands in order, the first from 00:00.
#[derive(Serialize, Deserialize, Clone, Debug, PartialEq, Default)]
#[serde(default)]
pub struct RunSet {
    pub day: usize,
    pub dir: usize,
    pub bands: Vec<Band>,
}

/// A time band: from `from` (minutes after midnight, up to 36:00) to where the next begins,
/// with the minutes of every segment (stop to next stop) of its direction.
#[derive(Serialize, Deserialize, Clone, Debug, PartialEq, Default)]
#[serde(default)]
pub struct Band {
    pub from: f32,
    pub run: Vec<f32>,
}

/// The timepoints of a direction (by the stops' object ids). No entry: every stop is one.
#[derive(Serialize, Deserialize, Clone, Debug, PartialEq, Default)]
#[serde(default)]
pub struct Timepoints {
    pub dir: usize,
    pub stops: Vec<i64>,
}

/// The minutes from each stop of a direction to the next, as its own times have them.
pub fn base_run(d: &Direction) -> Vec<f32> {
    let t = reg::fitted_times(d);
    t.windows(2).map(|w| (w[1] - w[0]).max(0.0)).collect()
}

impl RunSet {
    /// One band, all day, with the direction's own times.
    pub fn fresh(day: usize, dir: usize, d: &Direction) -> RunSet {
        RunSet { day, dir, bands: vec![Band { from: 0.0, run: base_run(d) }] }
    }

    /// Made to fit the direction's stops (a stop added or taken out since: its segment the
    /// direction's own), the bands in order and the first from 00:00.
    pub fn fit(&mut self, d: &Direction) {
        let base = base_run(d);
        if self.bands.is_empty() {
            self.bands.push(Band { from: 0.0, run: base.clone() });
        }
        for b in &mut self.bands {
            if b.run.len() != base.len() {
                let mut run = b.run.clone();
                run.truncate(base.len());
                run.extend(base[run.len()..].iter().copied());
                b.run = run;
            }
            b.from = b.from.clamp(0.0, DAY_SPAN);
        }
        self.bands.sort_by(|a, b| a.from.total_cmp(&b.from));
        self.bands.dedup_by(|a, b| (a.from - b.from).abs() < 0.5);
        self.bands[0].from = 0.0;
    }

    /// The band a minute of the day is in.
    pub fn band_at(&self, t: f32) -> usize {
        self.bands.iter().rposition(|b| b.from <= t + 1e-3).unwrap_or(0)
    }

    /// The running time of segment `i` for a bus that starts it at minute `t`.
    pub fn segment(&self, t: f32, i: usize) -> f32 {
        self.bands.get(self.band_at(t)).and_then(|b| b.run.get(i)).copied().unwrap_or(0.0)
    }

    /// A trip's time at each of its `n` stops when it is at stop `at` at minute `t`: forward
    /// segment by segment, each with the band it starts in, and back from `at` the same way (the
    /// start of a segment found so that it ends at the next stop's time).
    pub fn times(&self, at: usize, t: f32, n: usize) -> Vec<f32> {
        if n == 0 {
            return Vec::new();
        }
        let at = at.min(n - 1);
        let mut out = vec![0.0; n];
        out[at] = t;
        for i in at..n - 1 {
            out[i + 1] = out[i] + self.segment(out[i], i);
        }
        for i in (1..=at).rev() {
            let end = out[i];
            let mut s = end - self.segment(end, i - 1);
            for _ in 0..4 {
                let next = end - self.segment(s, i - 1);
                if (next - s).abs() < 1e-3 {
                    break;
                }
                s = next;
            }
            out[i - 1] = s;
        }
        out
    }

    /// Minutes a trip leaving at `t` takes from its first stop to its last.
    pub fn total(&self, t: f32, n: usize) -> f32 {
        self.times(0, t, n).last().copied().unwrap_or(t) - t
    }

    /// A band added from `from` (rounded, within 00:00 - 36:00) with the running times of the
    /// band it splits; the one there already when one begins at that minute. Returns it.
    pub fn add_band(&mut self, from: f32) -> usize {
        let from = from.round().clamp(0.0, DAY_SPAN - 1.0);
        if let Some(k) = self.bands.iter().position(|b| (b.from - from).abs() < 0.5) {
            return k;
        }
        let run = self.bands.get(self.band_at(from)).map(|b| b.run.clone()).unwrap_or_default();
        let k = self.bands.iter().position(|b| b.from > from).unwrap_or(self.bands.len());
        self.bands.insert(k, Band { from, run });
        k
    }

    /// Band `k` taken out (the one before runs on in its hours); never the last one left.
    pub fn remove_band(&mut self, k: usize) -> bool {
        if self.bands.len() <= 1 || k >= self.bands.len() {
            return false;
        }
        self.bands.remove(k);
        self.bands[0].from = 0.0;
        true
    }

    /// Band `k` begins at `from` instead (between the bands around it; the first stays at
    /// 00:00). Returns where it begins now.
    pub fn move_band(&mut self, k: usize, from: f32) -> f32 {
        if k == 0 || k >= self.bands.len() {
            return 0.0;
        }
        let lo = self.bands[k - 1].from + 1.0;
        let hi = self.bands.get(k + 1).map(|b| b.from - 1.0).unwrap_or(DAY_SPAN - 1.0);
        self.bands[k].from = from.round().clamp(lo, hi.max(lo));
        self.bands[k].from
    }
}

impl RunPlan {
    /// The running times of a day group and direction of `l`: as kept, fitted to the stops,
    /// else one band with the direction's own times.
    pub fn set(&self, l: &LineDesign, day: usize, dir: usize) -> RunSet {
        let Some(d) = l.directions.get(dir) else { return RunSet { day, dir, bands: vec![Band::default()] } };
        let mut s = self.sets.iter().find(|s| s.day == day && s.dir == dir).cloned().unwrap_or_else(|| RunSet::fresh(day, dir, d));
        s.fit(d);
        s
    }

    /// The running times of a day group and direction kept as `s` is.
    pub fn put(&mut self, s: RunSet) {
        match self.sets.iter_mut().find(|x| x.day == s.day && x.dir == s.dir) {
            Some(x) => *x = s,
            None => self.sets.push(s),
        }
    }

    /// Stop `k` of direction `dir` is a timepoint: the first and the last always, the others
    /// as chosen (every stop when nothing was chosen).
    pub fn is_timepoint(&self, dir: usize, d: &Direction, k: usize) -> bool {
        if k == 0 || k + 1 >= d.stops.len() {
            return true;
        }
        match self.timepoints.iter().find(|t| t.dir == dir) {
            Some(t) => d.stops.get(k).is_some_and(|s| t.stops.contains(&s.id)),
            None => true,
        }
    }

    /// Stop `k` of direction `dir` a timepoint or a plain stop (not the first or the last).
    pub fn toggle_timepoint(&mut self, dir: usize, d: &Direction, k: usize) {
        if k == 0 || k + 1 >= d.stops.len() {
            return;
        }
        let Some(id) = d.stops.get(k).map(|s| s.id) else { return };
        if !self.timepoints.iter().any(|t| t.dir == dir) {
            self.timepoints.push(Timepoints { dir, stops: d.stops.iter().map(|s| s.id).collect() });
        }
        let t = self.timepoints.iter_mut().find(|t| t.dir == dir).unwrap();
        match t.stops.iter().position(|x| *x == id) {
            Some(i) => {
                t.stops.remove(i);
            }
            None => t.stops.push(id),
        }
    }
}

/// The line's timeplan (an empty one when it has none yet).
pub fn plan_of(l: &LineDesign) -> RunPlan {
    l.timeplan.clone().unwrap_or_default()
}

/// The running times of a day group and direction of `l` (`RunPlan::set`).
pub fn run_set(l: &LineDesign, day: usize, dir: usize) -> RunSet {
    plan_of(l).set(l, day, dir)
}

/// The timetable a table of trips: the day patterns' own departures, every one the player's
/// to change then (as the planning's timetable editor and the line editor start one).
pub fn as_table(l: &mut LineDesign) {
    if !l.table_on {
        l.table = reg::table_from_patterns(l);
        l.table_on = true;
    }
}

// --- patterns and sides -------------------------------------------------------------------------

/// A column of a side's timetable: a stop of one of its patterns.
#[derive(Clone, Debug, PartialEq, Default)]
pub struct Column {
    pub id: i64,
    pub name: String,
}

/// One side of a line (OUTBOUND or INBOUND): its patterns (directions of the line, the main
/// one first), the columns their stops make together, and for each pattern the column of each
/// of its stops.
#[derive(Clone, Debug, PartialEq, Default)]
pub struct Side {
    pub patterns: Vec<usize>,
    pub columns: Vec<Column>,
    pub col_of: Vec<Vec<usize>>,
}

impl Side {
    /// The place of direction `dir` among the side's patterns.
    pub fn pattern(&self, dir: usize) -> Option<usize> {
        self.patterns.iter().position(|p| *p == dir)
    }
}

/// The short name a pattern has: the main one "-", the others A, B, C…
pub fn pattern_code(k: usize) -> String {
    match k {
        0 => "-".into(),
        k if k <= 26 => ((b'A' + (k - 1) as u8) as char).to_string(),
        k => format!("P{k}"),
    }
}

fn key(name: &str) -> String {
    name.trim().to_lowercase()
}

/// Two stops are the same column: the same object, or the same name (the stop across the road).
fn same_stop(a: &Column, id: i64, name: &str) -> bool {
    (a.id != 0 && a.id == id) || (!key(name).is_empty() && key(&a.name) == key(name))
}

/// How many stops two directions share in the same order (by name).
fn shared(a: &Direction, b: &Direction) -> usize {
    let (x, y): (Vec<String>, Vec<String>) = (a.stops.iter().map(|s| key(&s.name)).collect(), b.stops.iter().map(|s| key(&s.name)).collect());
    let mut dp = vec![vec![0usize; y.len() + 1]; x.len() + 1];
    for i in 0..x.len() {
        for j in 0..y.len() {
            dp[i + 1][j + 1] = if x[i] == y[j] { dp[i][j] + 1 } else { dp[i][j + 1].max(dp[i + 1][j]) };
        }
    }
    dp[x.len()][y.len()]
}

/// The two sides of a line: OUTBOUND with the first direction, INBOUND with the second, and
/// every further direction (a line of the map's variants) with the side whose main direction
/// it follows most, its first stop deciding a tie.
pub fn sides(l: &LineDesign) -> [Side; 2] {
    let mut out = [Side::default(), Side::default()];
    for (k, d) in l.directions.iter().enumerate() {
        let side = match k {
            0 => 0,
            1 => 1,
            _ => {
                let a = shared(d, &l.directions[0]);
                let b = shared(d, &l.directions[1]);
                if b > a {
                    1
                } else if a > b {
                    0
                } else {
                    let first = d.stops.first().map(|s| key(&s.name)).unwrap_or_default();
                    usize::from(l.directions[1].stops.first().is_some_and(|s| key(&s.name) == first))
                }
            }
        };
        out[side].patterns.push(k);
    }
    for s in out.iter_mut() {
        // the columns: the main pattern's stops, each other pattern's put in where it has them
        let mut cols: Vec<Column> = Vec::new();
        for &p in &s.patterns {
            let mut last: Option<usize> = None;
            for st in &l.directions[p].stops {
                let from = last.map(|x| x + 1).unwrap_or(0);
                match (from..cols.len()).find(|&j| same_stop(&cols[j], st.id, &st.name)) {
                    Some(j) => last = Some(j),
                    None => {
                        cols.insert(from, Column { id: st.id, name: st.name.trim().to_string() });
                        last = Some(from);
                    }
                }
            }
        }
        s.col_of = s
            .patterns
            .iter()
            .map(|&p| {
                let mut last: Option<usize> = None;
                l.directions[p]
                    .stops
                    .iter()
                    .map(|st| {
                        let from = last.map(|x| x + 1).unwrap_or(0);
                        let j = (from..cols.len()).find(|&j| same_stop(&cols[j], st.id, &st.name)).unwrap_or(from.min(cols.len().saturating_sub(1)));
                        last = Some(j);
                        j
                    })
                    .collect()
            })
            .collect();
        s.columns = cols;
    }
    out
}

/// The trip `t` of the table runs on day group `day` (a trip of a map's tour on its tour's
/// days, as `lines::trip_in_group` says; a trip of the player's on its own group, if the line's
/// kind of service runs then).
pub fn in_day(l: &LineDesign, t: &TableTrip, day: usize) -> bool {
    if l.map.is_none() && !l.service.allows(day) {
        return false;
    }
    reg::trip_in_group(l, t, day)
}

/// The trips of the table (their places in it) of a side on a day group, in order of their
/// departure.
pub fn rows(l: &LineDesign, day: usize, side: &Side) -> Vec<usize> {
    let mut v: Vec<usize> = l.table.iter().enumerate().filter(|(_, t)| !t.times.is_empty() && side.patterns.contains(&t.dir) && in_day(l, t, day)).map(|(i, _)| i).collect();
    v.sort_by(|a, b| departure(l, *a).total_cmp(&departure(l, *b)).then(a.cmp(b)));
    v
}

/// A trip's times as its direction's stops are now (`lines::trip_times`).
pub fn trip(l: &LineDesign, i: usize) -> Vec<f32> {
    l.table.get(i).map(|t| reg::trip_times(l, t)).unwrap_or_default()
}

pub fn departure(l: &LineDesign, i: usize) -> f32 {
    l.table.get(i).map(TableTrip::departure).unwrap_or(0.0)
}

// --- changing the trips --------------------------------------------------------------------------

/// The trips `rows[k..]` all `by` minutes later (earlier when negative).
pub fn shift_from(l: &mut LineDesign, rows: &[usize], k: usize, by: f32) {
    if by.abs() < 1e-3 {
        return;
    }
    for &i in rows.iter().skip(k) {
        if let Some(t) = l.table.get_mut(i) {
            for x in &mut t.times {
                *x += by;
            }
        }
    }
}

/// Trip `rows[k]` starts at `start`: it and every trip after it move with it.
pub fn set_start(l: &mut LineDesign, rows: &[usize], k: usize, start: f32) {
    let Some(&i) = rows.get(k) else { return };
    let by = start.max(0.0) - departure(l, i);
    // (not before midnight)
    let floor = rows.iter().skip(k).map(|&r| departure(l, r)).fold(f32::MAX, f32::min);
    shift_from(l, rows, k, by.max(-floor));
}

/// Trip `rows[k]` leaves `headway` minutes after the one before it: it and every trip after
/// it move with it (the first trip has no headway).
pub fn set_headway(l: &mut LineDesign, rows: &[usize], k: usize, headway: f32) {
    if k == 0 || k >= rows.len() {
        return;
    }
    let start = departure(l, rows[k - 1]) + headway.max(0.0);
    set_start(l, rows, k, start);
}

/// The time of trip `i` at its stop `stop` typed over (an override).
pub fn set_cell(l: &mut LineDesign, i: usize, stop: usize, t: f32) {
    let times = trip(l, i);
    if let Some(x) = l.table.get_mut(i) {
        x.times = times;
        if let Some(c) = x.times.get_mut(stop) {
            *c = t.max(0.0);
        }
    }
}

/// The time of trip `i` at every stop worked out again from the running times, from its
/// departure (its overrides gone).
pub fn revert(l: &mut LineDesign, i: usize, set: &RunSet) {
    let Some(t) = l.table.get(i) else { return };
    let n = l.directions.get(t.dir).map(|d| d.stops.len()).unwrap_or(0);
    let dep = t.departure();
    l.table[i].times = set.times(0, dep, n);
}

/// A trip of direction `dir` on day group `day` leaving at `dep`, its times from the running
/// times. Returns its place in the table.
pub fn add_trip(l: &mut LineDesign, day: usize, dir: usize, dep: f32, set: &RunSet) -> Option<usize> {
    let n = l.directions.get(dir).map(|d| d.stops.len()).filter(|n| *n >= 2)?;
    as_table(l);
    l.table.push(TableTrip { dir, day, times: set.times(0, dep.max(0.0), n), tour: String::new() });
    Some(l.table.len() - 1)
}

/// Trip `i` taken out of the table.
pub fn delete_trip(l: &mut LineDesign, i: usize) -> bool {
    if i < l.table.len() {
        l.table.remove(i);
        true
    } else {
        false
    }
}

/// Headways as typed: "10", or several to take in turn ("10,20" alternates). None: not
/// minutes, or one below a minute.
pub fn parse_headways(s: &str) -> Option<Vec<f32>> {
    let v: Option<Vec<f32>> = s.split([',', ';', '/', ' ']).filter(|x| !x.trim().is_empty()).map(|x| x.trim().replace(',', ".").parse::<f32>().ok().filter(|m| *m >= 1.0 && *m <= 600.0)).collect();
    v.filter(|v| !v.is_empty())
}

/// The trips (each its time at every one of `n` stops) leaving the control point `control`
/// from `first` to `last` every `headways` minutes (in turn), the other stops' times from the
/// running times.
pub fn generate(set: &RunSet, n: usize, control: usize, first: f32, last: f32, headways: &[f32]) -> Vec<Vec<f32>> {
    let mut out = Vec::new();
    if n < 2 || headways.is_empty() || last < first {
        return out;
    }
    let mut t = first;
    let mut k = 0;
    while t <= last + 1e-3 && out.len() < 1000 {
        out.push(set.times(control, t, n));
        t += headways[k % headways.len()].max(1.0);
        k += 1;
    }
    out
}

/// Trips generated by `generate` put into the table (direction `dir`, day group `day`).
/// Returns how many.
pub fn add_generated(l: &mut LineDesign, day: usize, dir: usize, trips: Vec<Vec<f32>>) -> usize {
    let n = trips.len();
    if n == 0 {
        return 0;
    }
    as_table(l);
    l.table.extend(trips.into_iter().map(|times| TableTrip { dir, day, times, tour: String::new() }));
    n
}

/// How far each time of a trip is off what the running times give from its departure (an
/// override where it is not 0).
pub fn offsets(set: &RunSet, times: &[f32]) -> Vec<f32> {
    let Some(&dep) = times.first() else { return Vec::new() };
    let want = set.times(0, dep, times.len());
    times.iter().zip(want).map(|(a, b)| a - b).collect()
}

/// The running times of a day group and direction changed from `old` to `new`: every trip of
/// it takes them, each override kept as the offset it was (as Optibus does: a change of the
/// running times updates the trips at once).
pub fn retime(l: &mut LineDesign, day: usize, dir: usize, old: &RunSet, new: &RunSet) {
    let idx: Vec<usize> = l.table.iter().enumerate().filter(|(_, t)| t.dir == dir && in_day(l, t, day)).map(|(i, _)| i).collect();
    for i in idx {
        let times = trip(l, i);
        let off = offsets(old, &times);
        let Some(&dep) = times.first() else { continue };
        let want = new.times(0, dep, times.len());
        l.table[i].times = want.iter().zip(off).map(|(w, o)| w + o).collect();
    }
}

// --- figures --------------------------------------------------------------------------------------

/// Departures in each hour from 00 to 35.
pub fn by_hour(l: &LineDesign, rows: &[usize]) -> [u32; 36] {
    let mut out = [0u32; 36];
    for &i in rows {
        let h = (departure(l, i) / 60.0).floor().clamp(0.0, 35.0) as usize;
        out[h] += 1;
    }
    out
}

/// Trips of each pattern of a side.
pub fn by_pattern(l: &LineDesign, side: &Side, rows: &[usize]) -> Vec<u32> {
    let mut out = vec![0u32; side.patterns.len()];
    for &i in rows {
        if let Some(k) = l.table.get(i).and_then(|t| side.pattern(t.dir)) {
            out[k] += 1;
        }
    }
    out
}

