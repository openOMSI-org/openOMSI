#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Level {
    Error,
    Warning,
}

/// A kind of issue of the timeplan: how bad, the text (an interface text, `%{n}` the count),
/// how often, and the trips it concerns (places in the table).
#[derive(Clone, Debug, PartialEq)]
pub struct Issue {
    pub level: Level,
    pub text: &'static str,
    pub n: usize,
    pub trips: Vec<usize>,
}

pub const OVERLAP: &str = "%{n} trip(s) leave at the same minute as another trip of their pattern";
pub const OVERTAKE: &str = "%{n} trip(s) arrive after the trip that leaves after them";
pub const FALLING: &str = "%{n} trip(s) of the table reach a stop before they left the one before";
pub const NEGATIVE: &str = "%{n} running time(s) below zero";
pub const ZERO: &str = "%{n} running time(s) of zero minutes";
pub const NO_STOPS: &str = "%{n} pattern(s) without stops";
pub const LATE: &str = "%{n} trip(s) run past 36:00";
pub const NO_TRIPS: &str = "No trips on this day";

impl Issue {
    pub fn english(&self) -> String {
        self.text.replace("%{n}", &self.n.to_string())
    }
}

/// Every English text of the validation (for the translations' check).
pub fn texts() -> [&'static str; 8] {
    [OVERLAP, OVERTAKE, FALLING, NEGATIVE, ZERO, NO_STOPS, LATE, NO_TRIPS]
}

/// What is wrong with the timeplan of a day group (both sides), errors first.
pub fn issues(l: &LineDesign, day: usize) -> Vec<Issue> {
    let mut out: Vec<Issue> = Vec::new();
    let mut push = |level, text, trips: Vec<usize>, n: usize| {
        if n > 0 {
            out.push(Issue { level, text, n, trips });
        }
    };
    let [a, b] = sides(l);
    let mut all: Vec<usize> = Vec::new();
    let no_stops = a.patterns.iter().chain(&b.patterns).filter(|&&p| l.directions[p].stops.len() < 2).count();
    push(Level::Error, NO_STOPS, Vec::new(), no_stops);
    for side in [&a, &b] {
        all.extend(rows(l, day, side));
    }
    // overlapping and overtaking, per pattern
    let (mut overlap, mut overtake) = (Vec::new(), Vec::new());
    for &dir in a.patterns.iter().chain(&b.patterns) {
        let mut mine: Vec<(f32, f32, usize)> = all.iter().filter(|&&i| l.table[i].dir == dir).map(|&i| {
            let t = trip(l, i);
            (t.first().copied().unwrap_or(0.0), t.last().copied().unwrap_or(0.0), i)
        }).collect();
        mine.sort_by(|x, y| x.0.total_cmp(&y.0));
        for w in mine.windows(2) {
            if (w[1].0 - w[0].0).abs() < 0.5 {
                overlap.extend([w[0].2, w[1].2]);
            } else if w[1].1 < w[0].1 - 1e-3 {
                overtake.push(w[1].2);
            }
        }
    }
    overlap.sort_unstable();
    overlap.dedup();
    let n = overlap.len();
    push(Level::Error, OVERLAP, overlap, n);
    let falling: Vec<usize> = all.iter().copied().filter(|&i| TableTrip { times: trip(l, i), ..TableTrip::default() }.first_fall().is_some()).collect();
    let n = falling.len();
    push(Level::Error, FALLING, falling, n);
    let late: Vec<usize> = all.iter().copied().filter(|&i| trip(l, i).iter().any(|t| *t > DAY_SPAN + 1e-3)).collect();
    let n = late.len();
    push(Level::Error, LATE, late, n);
    // the running times of the day group's patterns
    let plan = plan_of(l);
    let (mut neg, mut zero) = (0, 0);
    for &dir in a.patterns.iter().chain(&b.patterns) {
        if l.directions[dir].stops.len() < 2 {
            continue;
        }
        for band in &plan.set(l, day, dir).bands {
            neg += band.run.iter().filter(|m| **m < -1e-3).count();
            zero += band.run.iter().filter(|m| m.abs() <= 1e-3).count();
        }
    }
    push(Level::Error, NEGATIVE, Vec::new(), neg);
    let n = overtake.len();
    push(Level::Warning, OVERTAKE, overtake, n);
    push(Level::Warning, ZERO, Vec::new(), zero);
    if all.is_empty() && (l.map.is_some() || l.service.allows(day)) {
        out.push(Issue { level: Level::Warning, text: NO_TRIPS, n: 0, trips: Vec::new() });
    }
    out
}

/// The timeplan of a day group has no error (what blocks its saving).
pub fn clean(l: &LineDesign, day: usize) -> bool {
    issues(l, day).iter().all(|i| i.level != Level::Error)
}

// --- times as typed and shown ---------------------------------------------------------------------

/// Minutes as the timeplan shows them: "07:05", past midnight on ("24:02").
pub fn hm(minutes: f32) -> String {
    let m = minutes.round() as i32;
    let sign = if m < 0 { "-" } else { "" };
    let m = m.abs();
    format!("{sign}{:02}:{:02}", m / 60, m % 60)
}

/// A time typed: "7:05", "07.05", "0705", "705", up to 36:00 (None: not a time).
pub fn parse_time(s: &str) -> Option<f32> {
    let s = s.trim();
    let (h, m) = match s.split_once([':', '.', 'h']) {
        Some((h, m)) => (h.trim().parse::<i32>().ok()?, m.trim().parse::<i32>().ok()?),
        None if s.len() >= 3 && s.chars().all(|c| c.is_ascii_digit()) => (s[..s.len() - 2].parse().ok()?, s[s.len() - 2..].parse().ok()?),
        None if !s.is_empty() && s.len() <= 2 && s.chars().all(|c| c.is_ascii_digit()) => (s.parse().ok()?, 0),
        None => return None,
    };
    ((0..=36).contains(&h) && (0..60).contains(&m) && h * 60 + m <= DAY_SPAN as i32).then_some((h * 60 + m) as f32)
}

/// Minutes typed ("7", "7.5", "7 m"; None: not a number, or more than a day).
pub fn parse_minutes(s: &str) -> Option<f32> {
    let s = s.trim().trim_end_matches('m').trim().replace(',', ".");
    s.parse::<f32>().ok().filter(|m| m.is_finite() && m.abs() <= 1440.0)
}

/// Minutes as a running-time cell shows them ("7", "7.5").
pub fn minutes_text(m: f32) -> String {
    if (m - m.round()).abs() < 0.05 {
        format!("{}", m.round() as i32)
    } else {
        format!("{m:.1}")
    }
}

// --- the hand-over to scheduling ------------------------------------------------------------------

/// The weekdays (0 Monday) of a day group.
pub fn weekdays(day: usize) -> Vec<u8> {
    match day {
        0 => (0..5).collect(),
        1 => vec![5],
        _ => vec![6],
    }
}

/// The scheduling studio makes its blocks and duties of `line` anew on the weekdays of day
/// group `day` (Optibus's "Refresh" of an UNSYNCED schedule): what was laid out by hand for it
/// there goes, the automatic blocks and cuts again. Returns whether anything went.
pub fn resync(c: &mut Company, line: &str, day: usize) -> bool {
    let wds = weekdays(day);
    let same = |a: &str| a.trim().eq_ignore_ascii_case(line.trim());
    let before = c.planning.layouts.len() + c.planning.joined.len();
    c.planning.layouts.retain(|x| !(wds.contains(&x.weekday) && same(&x.line)));
    c.planning.joined.retain(|j| !(wds.contains(&j.weekday) && j.pieces.iter().any(|p| same(&p.line))));
    before != c.planning.layouts.len() + c.planning.joined.len()
}

